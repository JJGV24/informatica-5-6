def main():
#Augmented Assigment Operator
    score = 10
    score += 10
    print(score)

    #Substraction Assignment Operator
    #x-=y
    score -= 5
    print(score)

    #Multiplication Assignment Operator
    #x *= y
    score *= 4
    print(score)

    #Division Assignment Operator
    # x /= Y
    score /= 2
    print(int(score))


if __name__=="__main__":
    main()
